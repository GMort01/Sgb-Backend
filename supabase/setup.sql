-- Esquema inicial de SGB Unimadeira para Supabase (PostgreSQL).
-- Ejecutar en el SQL Editor de Supabase; el esquema y los datos semilla
-- pueden volver a aplicarse sin duplicar registros de demostracion.
-- Las contrasenas se asignan con bcrypt al iniciar el backend.

BEGIN;

CREATE TABLE IF NOT EXISTS public.usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificacion TEXT NOT NULL UNIQUE,
    codigo TEXT NOT NULL UNIQUE,
    nombres TEXT NOT NULL,
    apellidos TEXT NOT NULL,
    correo TEXT NOT NULL UNIQUE,
    rol TEXT NOT NULL,
    plan TEXT,
    semestre INTEGER,
    password_hash TEXT
);

CREATE TABLE IF NOT EXISTS public.recursos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    coleccion TEXT NOT NULL,
    disponible BOOLEAN NOT NULL DEFAULT TRUE,
    autor TEXT,
    ejemplares INTEGER NOT NULL DEFAULT 1,
    estado TEXT NOT NULL DEFAULT 'Disponible',
    isbn TEXT,
    resumen TEXT,
    fecha_publicacion TEXT,
    dimensiones TEXT,
    encuadernacion TEXT,
    issn TEXT,
    periodicidad TEXT,
    formato TEXT,
    tipo_equipo TEXT,
    numero_equipo TEXT,
    marca TEXT,
    modelo TEXT,
    cargador BOOLEAN,
    funda BOOLEAN,
    ejemplares_totales INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT recursos_ejemplares_no_negativos CHECK (ejemplares >= 0),
    CONSTRAINT recursos_ejemplares_totales_no_negativos CHECK (ejemplares_totales >= 0)
);

CREATE TABLE IF NOT EXISTS public.prestamos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT NOT NULL,
    usuario_id INTEGER REFERENCES public.usuarios(id),
    codigo_recurso TEXT NOT NULL,
    recurso_id INTEGER REFERENCES public.recursos(id),
    fecha_salida TEXT NOT NULL,
    fecha_devolucion TEXT NOT NULL,
    renovaciones_restantes INTEGER NOT NULL DEFAULT 1,
    estado TEXT NOT NULL DEFAULT 'Activo',
    medio_entrega TEXT NOT NULL DEFAULT 'Regular',
    bibliotecario_id INTEGER REFERENCES public.usuarios(id)
);

CREATE TABLE IF NOT EXISTS public.reservas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT NOT NULL,
    usuario_id INTEGER REFERENCES public.usuarios(id),
    codigo_recurso TEXT NOT NULL,
    recurso_id INTEGER REFERENCES public.recursos(id),
    fecha_reserva TEXT NOT NULL,
    posicion INTEGER NOT NULL DEFAULT 1,
    estado TEXT NOT NULL DEFAULT 'Espera' CHECK (estado IN ('Espera', 'Apartada')),
    vence_en TIMESTAMPTZ,
    CONSTRAINT reservas_estado_vencimiento_coherentes CHECK (
        (estado = 'Espera' AND vence_en IS NULL)
        OR (estado = 'Apartada' AND vence_en IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS public.multas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT NOT NULL,
    concepto TEXT NOT NULL,
    monto NUMERIC(10, 2) NOT NULL CHECK (monto > 0),
    fecha TEXT NOT NULL DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'America/Bogota')::DATE)::TEXT,
    estado TEXT NOT NULL DEFAULT 'Pendiente',
    usuario_id INTEGER REFERENCES public.usuarios(id),
    prestamo_id INTEGER REFERENCES public.prestamos(id)
);
ALTER TABLE public.multas
    ADD COLUMN IF NOT EXISTS prestamo_id INTEGER REFERENCES public.prestamos(id);

CREATE TABLE IF NOT EXISTS public.actividades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    descripcion TEXT NOT NULL,
    fecha TEXT NOT NULL,
    hora TEXT NOT NULL,
    lugar TEXT NOT NULL,
    cupos INTEGER NOT NULL DEFAULT 20
);

CREATE TABLE IF NOT EXISTS public.inscripciones_actividades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actividad_id INTEGER NOT NULL REFERENCES public.actividades(id),
    usuario_id INTEGER NOT NULL REFERENCES public.usuarios(id),
    fecha_inscripcion TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::TEXT,
    UNIQUE (actividad_id, usuario_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_recursos_numero_equipo
    ON public.recursos (numero_equipo)
    WHERE numero_equipo IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_recursos_coleccion_titulo
    ON public.recursos (coleccion, titulo);
CREATE INDEX IF NOT EXISTS idx_prestamos_usuario_estado
    ON public.prestamos (usuario_id, estado);
CREATE INDEX IF NOT EXISTS idx_prestamos_recurso_estado
    ON public.prestamos (recurso_id, estado);
CREATE INDEX IF NOT EXISTS idx_reservas_recurso_posicion
    ON public.reservas (recurso_id, estado, posicion, fecha_reserva);
CREATE INDEX IF NOT EXISTS idx_reservas_apartadas_vencimiento
    ON public.reservas (vence_en)
    WHERE estado = 'Apartada';
CREATE INDEX IF NOT EXISTS idx_multas_usuario_estado
    ON public.multas (usuario_id, estado);
CREATE UNIQUE INDEX IF NOT EXISTS idx_multas_prestamo_fecha
    ON public.multas (prestamo_id, fecha)
    WHERE prestamo_id IS NOT NULL;

