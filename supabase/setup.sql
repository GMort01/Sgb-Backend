    perfiles.prefijo || '-' || lpad(serie.numero::TEXT, 3, '0'),
    CASE
        WHEN perfiles.rol = 'Bibliotecario' AND serie.numero = 1 THEN 'Lucia'
        WHEN perfiles.rol = 'Estudiante' AND serie.numero = 1 THEN 'Valeria'
        WHEN perfiles.rol = 'Estudiante' AND serie.numero = 2 THEN 'Mateo'
        ELSE perfiles.nombre_base
    END,
    CASE
        WHEN perfiles.rol = 'Bibliotecario' AND serie.numero = 1 THEN 'Bibliotecaria'
        WHEN perfiles.rol = 'Estudiante' AND serie.numero = 1 THEN 'Demo'
        WHEN perfiles.rol = 'Estudiante' AND serie.numero = 2 THEN 'Prueba'
        ELSE lpad(serie.numero::TEXT, 3, '0')
    END,
    CASE
        WHEN perfiles.rol = 'Bibliotecario' AND serie.numero = 1 THEN 'lucia.demo@example.test'
        WHEN perfiles.rol = 'Estudiante' AND serie.numero = 1 THEN 'valeria.demo@example.test'
        WHEN perfiles.rol = 'Estudiante' AND serie.numero = 2 THEN 'mateo.demo@example.test'
        ELSE perfiles.sufijo_correo || lpad(serie.numero::TEXT, 3, '0') || '@demo.unimadeira.test'
    END,
    perfiles.rol,
    CASE WHEN perfiles.rol = 'Estudiante' THEN 'Ingeniería de Software' END,
    CASE WHEN perfiles.rol = 'Estudiante' THEN ((serie.numero - 1) % 10) + 1 END
FROM (VALUES
    ('Estudiante', 'EST', 50, 'Estudiante', 'estudiante'),
    ('Profesor', 'PROF', 10, 'Profesor', 'profesor'),
    ('Bibliotecario', 'BIB', 3, 'Bibliotecario', 'bibliotecario')
) AS perfiles(rol, prefijo, cantidad, nombre_base, sufijo_correo)
CROSS JOIN LATERAL generate_series(1, perfiles.cantidad) AS serie(numero)
ON CONFLICT DO NOTHING;

